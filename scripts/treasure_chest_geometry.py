"""Geometry descriptors for the paper's box with a superelliptic cap.

These are input geometry sites and feature topology. Output face and volume
nodes are generated by kernelpack's shared hierarchical/PDS routines.
"""
import numpy as np
import jax.numpy as jnp
from kernelpack.geometry.core import project_to_best_fit_plane
from kernelpack.nodes import DomainNodeGenerator
from kernelpack.geometry.parametric_pu import ParametricSurfaceData

L, D, A, B, P = 1.2, .6, .6, .35, 4


def cap_normal(points):
    x = np.asarray(points)
    n = np.column_stack((2*(x[:, 0]-L)/D**2,
        P*np.sign(x[:, 1])*np.abs(x[:, 1])**(P-1)/A**P,
        P*np.sign(x[:, 2])*np.abs(x[:, 2])**(P-1)/B**P))
    return n / np.linalg.norm(n, axis=1)[:, None]


def descriptors(h, *, fit_resolution=21, use_pu=True):
    """Supply physical faces and features to the shared geometric model.

    fit_resolution controls data-site refinement for parametric geometry accuracy
    studies. It changes geometry input resolution, not output-node spacing h.
    use_pu=False reproduces the archived four cap charts.
    """
    if int(fit_resolution) != fit_resolution or fit_resolution < 3:
        raise ValueError("fit_resolution must be an integer at least 3")
    fit_resolution = int(fit_resolution)
    outline_resolution = max(17, round(257 * fit_resolution / 21))
    radial_resolution = max(3, round(9 * fit_resolution / 21))
    data, curves, dims, constants, flips, labels = [], [], [], [], [], []
    def plane(outline, dim, value, flip, label):
        data.append(jnp.asarray(outline)); curves.append(True)
        dims.append(dim); constants.append(value); flips.append(flip); labels.append(label)
    def rectangle(u, v):
        return np.array([[u[0],v[0]],[u[1],v[0]],[u[1],v[1]],[u[0],v[1]]])
    plane(rectangle((-A,A),(-B,B)),0,0,True,'back')
    for sign in (-1,1):
        plane(rectangle((0,L),(-B,B)),1,sign*A,sign<0,f'side_y_{sign}')
        plane(rectangle((0,L),(-A,A)),2,sign*B,sign<0,f'side_z_{sign}')
    # Complementary coordinate charts resolve the quarter superellipse all
    # the way to both axes, without the singular derivative of one graph.
    split = 2**(-1/P)
    t = np.linspace(0,split,outline_resolution)
    rim_quarter = np.vstack((np.column_stack((A*(1-t**P)**(1/P),B*t)),
        np.column_stack((A*t[::-1],B*(1-t[::-1]**P)**(1/P)))[1:]))
    fit_t = np.linspace(0,split,fit_resolution)
    fit_rim = np.vstack((np.column_stack((A*fit_t,B*(1-fit_t**P)**(1/P))),
        np.column_stack((A*(1-fit_t**P)**(1/P),B*fit_t))))
    scales = np.unique(np.r_[np.linspace(0,.9,radial_resolution),
        (1-np.linspace(0,np.sqrt(1-.9**P),radial_resolution)**2)**(1/P)])
    for sy in (-1,1):
        for sz in (-1,1):
            # Ordered concave footprint, including its curved inner boundary.
            shoulder = np.vstack(([A,0],[A,B],[0,B],rim_quarter[::-1][1:-1]))
            shoulder *= np.array([sy,sz])
            plane(shoulder,0,L,False,f'shoulder_{sy}_{sz}')
            s = np.repeat(scales,len(fit_rim))
            yz = np.tile(fit_rim,(len(scales),1))*s[:,None]
            xyz = np.column_stack((L+D*np.sqrt(np.maximum(0,1-s**P)),sy*yz[:,0],sz*yz[:,1]))
            xyz = np.unique(np.round(xyz,14),axis=0)
            flip=False
            if not use_pu:
                _,_,basis = project_to_best_fit_plane(jnp.asarray(xyz))
                orientation = np.cross(np.asarray(basis[:,0]),np.asarray(basis[:,1]))
                flip = bool(orientation @ cap_normal(xyz.mean(axis=0)[None,:])[0] < 0)
            data.append(jnp.asarray(xyz)); curves.append(False); dims.append(-1)
            constants.append(0); flips.append(flip); labels.append(f'cap_{sy}_{sz}')
    # Feature sites, normals and priorities are derived by the node generator from the
    # trimming loops of these pieces (kernelpack.geometry.features).
    rims = [np.column_stack((np.full(len(rim_quarter), L), sy*rim_quarter[:, 0], sz*rim_quarter[:, 1]))
            for sy in (-1, 1) for sz in (-1, 1)]
    if use_pu:
        cap_ids=[i for i,label in enumerate(labels) if label.startswith('cap_')]
        positions=np.unique(np.vstack([np.asarray(data[i]) for i in cap_ids]),axis=0)
        boundary=np.unique(np.vstack(rims),axis=0)
        order=np.argsort(np.arctan2(boundary[:,2]/B,boundary[:,1]/A))
        boundary=boundary[order]
        # The example supplies geometry sites and known feature curves only.
        # Parameterization, cover, indicators and refinement are all shared.
        if __package__:
            from .parametric_geometry_convergence_study import domed_square_patch_points
        else:
            from parametric_geometry_convergence_study import domed_square_patch_points
        checks=domed_square_patch_points('dome',1537)
        cap=ParametricSurfaceData.from_geometry(positions,[boundary],normals=cap_normal(positions),
            validation_positions=checks,validation_normals=cap_normal(checks))
        retain=[i for i in range(len(data)) if i not in cap_ids]
        data=[data[i] for i in retain]+[cap]
        curves=[curves[i] for i in retain]+[False]
        dims=[dims[i] for i in retain]+[-1]
        constants=[constants[i] for i in retain]+[0.]
        flips=[flips[i] for i in retain]+[False]
        labels=[labels[i] for i in retain]+['cap']
    return dict(bdry_desc=data,is_bdry_curve=curves,is_smooth_curve=[False]*len(data),
        constants=constants,constant_dim=dims,flip_normal=flips), labels


def build_boundary(h, seed=11, backend='warp'):
    description, labels = descriptors(h)
    surface = DomainNodeGenerator().build_piecewise_smooth_boundary_hierarchical(
        **description,radius=h,seed=seed,backend=backend,method=1,supersample_fac=2)
    return surface, labels
