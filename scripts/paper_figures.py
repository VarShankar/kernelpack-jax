def capital(s):
    return s[:1].upper() + s[1:]


def sci(x):
    e = int(math.floor(math.log10(x)))
    return f"${x / 10 ** e:.1f}\\times10^{{{e}}}$"


# ---------------------------------------------------------------- data
def load_forward():
    return [r for r in json.load(open(F / "seed11/results.json")) if r["status"] == "ok"]


def load_inverse(problem, path=None):
    latest = {}
    for line in open((I / problem if path is None else path) / "results.jsonl"):
        r = json.loads(line)
        latest[(r["geometry"], r["h"], r["order"], r["family"])] = r
    return list(latest.values())


def dim_of(geometry):
    return dict((g, d) for g, _, d in GEOMS + OGEOMS)[geometry]


def curves(rows, key):
    """{(geometry, order): {family: [(h, N^{-1/d}, value)]}}."""
    out = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rows:
        x = r["physical_nodes"] ** (-1 / dim_of(r["geometry"]))
        out[(r["geometry"], r["order"])][r["family"]].append((r["h"], x, r[key]))
    return out


def slope(points):
    pts = [(x, e) for h, x, e in points if h <= H_FIT and e > 0]
    if len(pts) < 2:
        return np.nan
    return np.polyfit(np.log([p[0] for p in pts]), np.log([p[1] for p in pts]), 1)[0]


# ---------------------------------------------------------------- figures
def worst_curve(fams):
    """Largest value over the families at each cloud: [(h, N^{-1/d}, value)] sorted by N^{-1/d}."""
    best = {}
    for pts in fams.values():
        for h, x, e in pts:
            if (h, x) not in best or e > best[(h, x)]:
                best[(h, x)] = e
    return sorted(((h, x, e) for (h, x), e in best.items()), key=lambda t: t[1])


def fit_line(pts):
    """Least-squares fit of log e against log x over h <= H_FIT: (slope, intercept, x range) or None."""
    q = [(x, e) for h, x, e in pts if h <= H_FIT and e > 0]
    if len(q) < 2:
        return None
    lx, le = np.log([a for a, _ in q]), np.log([b for _, b in q])
    k, c = np.polyfit(lx, le, 1)
    return k, c, min(a for a, _ in q), max(a for a, _ in q)


def convergence_data(panels, ylabel, geoms=GEOMS):
    """Data of a convergence figure for the MATLAB plotting script: rows = problems, columns = geometries."""
    rows = []
    for name, data in panels:
        cols = []
        for g, gname, d in geoms:
            cur = []
            for p in ORDERS:
                pts = worst_curve(data.get((g, p), {}))
                if not pts:
                    continue
                f = fit_line(pts)
                cur.append(dict(p=p, h=[h for h, _, _ in pts], x=[x for _, x, _ in pts], y=[e for _, _, e in pts],
                                fit=None if f is None else dict(k=f[0], c=f[1], x0=f[2], x1=f[3])))
            cols.append(dict(geometry=capital(gname), d=d, curves=cur))
        rows.append(dict(title=capital(name), panels=cols))
    return dict(ylabel=ylabel, rows=rows)


def timings_data(fwd):
    """Data of the timing figure: setup (node generation; operator setup of one cloud and order = shared Laplacian setup + Darcy setup) and time per SBDF3 step."""
    val = json.load(open(CLOUDS / "validation.json"))
    def series(name, p, by_geom):
        out = []
        for g, gname, d in GEOMS:
            pts = sorted(by_geom[g])
            out.append(dict(name=name, p=p, geometry=g, N=[n for n, _ in pts], t=[t for _, t in pts]))
        pts = sorted(by_geom["treasure_chest"])
        a, c = np.polyfit(np.log([n for n, _ in pts]), np.log([t for _, t in pts]), 1)
        return out, dict(name=name, p=p, a=float(a), c=float(c), N0=pts[0][0], N1=pts[-1][0])
    setup, setup_fits = [], []
    nodes = {g: [(V["n_interior"] + V["n_boundary"], sum(V["timing"].values()))
                 for V in (val[f"{g}_h{h:.2f}_s11"] for h in (.16, .12, .08, .06, .04))] for g, _, _ in GEOMS}
    s_, f_ = series("Nodes", 0, nodes); setup += s_; setup_fits.append(f_)
    def median_by_N(rows, value):
        pts = {}
        for r in rows:
            pts.setdefault(r["physical_nodes"], []).append(value(r))
        return sorted((n, float(np.median(t))) for n, t in pts.items())
    parts = {}
    for key, prob, value in (("darcy", "darcy", lambda r: r["solve_s"]), ("rd", "rd", lambda r: r["rollout_s"] / r["steps"])):
        ser, fts = [], []
        for p in ORDERS:
            by = {g: median_by_N([r for r in fwd if r["geometry"] == g and r["problem"] == prob and r["order"] == p
                                  and r.get("solve_s" if prob == "darcy" else "rollout_s")], value) for g, _, _ in GEOMS}
            s_, f_ = series(f"p={p}", p, by); ser += s_; fts.append(f_)
        parts[key] = dict(series=ser, fits=fts)
    step, step_fits = [], []
    for p in ORDERS:
        asm = {g: sorted({(r["physical_nodes"], r["shared_setup_s"] + r["setup_s"]) for r in fwd if r["geometry"] == g and r["problem"] == "darcy"
                          and r["order"] == p and r["family"] == "constant" and r.get("setup_s")}) for g, _, _ in GEOMS}
        s_, f_ = series(f"p={p}", p, asm); setup += s_; setup_fits.append(f_)
        st = {g: sorted({(r["physical_nodes"], r["rollout_s"] / r["steps"]) for r in fwd if r["geometry"] == g
                         and r["problem"] == "ad" and r["order"] == p and r.get("rollout_s")}) for g, _, _ in GEOMS}
        s_, f_ = series(f"p={p}", p, st); step += s_; step_fits.append(f_)
    return dict(setup=dict(series=setup, fits=setup_fits), step=dict(series=step, fits=step_fits), **parts)


def end_to_end_table(fwd, path, h=0.04):
    """Wall-clock seconds of every stage on the finest clouds: node generation, operator setup (shared Laplacian
    setup + Darcy setup), one forward solve per problem (Darcy solve, RD and AD rollouts; medians over the
    families), and one inverse solve per problem (median fit time over the families, warm-started)."""
    val = json.load(open(CLOUDS / "validation.json"))
    inv = {prob: [r for r in load_inverse(prob) if r["status"] == "ok" and r.get("fit_s")] for prob in ("darcy", "rd", "transport")}
    med = lambda v: float(np.median(v)) if v else float("nan")
    fmt = lambda t: "--" if not np.isfinite(t) else ("$<0.01$" if t < 0.005 else f"{t:.2f}" if t < 10 else f"{t:.0f}")
    lines = [r"\begin{table}[tbp]", r"\centering",
             r"\caption{Wall-clock seconds of the stages of Algorithms~\ref{alg:node_gen}--\ref{alg:inverse} on the finest clouds, "
             r"$h=" + f"{h:g}" + r"$, on one NVIDIA RTX 5090, including just-in-time compilation. Setup: stencils, weights, assembly, "
             r"stability check, and factorization for one cloud and order. RD: reaction--diffusion, AD: advection--diffusion. Forward and inverse solves: medians over the parameter families. "
             r"The forward solves of RD and AD integrate to $t=T$. The inverse solves are warm-started from the next coarser cloud and share the setup.}",
             r"\label{tab:end_to_end}", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{@{}llrrrrrrrrr@{}}", r"\toprule",
             r"& & & & & \multicolumn{3}{c}{Forward solve} & \multicolumn{3}{c}{Inverse solve}\\",
             r"\cmidrule(lr){6-8}\cmidrule(l){9-11}",
             r"Geometry & $p$ & $N$ & Nodes & Setup & Darcy & RD & AD & Darcy & RD & Transport\\", r"\midrule"]
    for gi, (g, gname, d) in enumerate(GEOMS):
        V = val[f"{g}_h{h:.2f}_s11"]
        tn = sum(V["timing"].values())
        for p in ORDERS:
            rows = lambda prob: [r for r in fwd if r["geometry"] == g and r["problem"] == prob and r["order"] == p and abs(r["h"] - h) < 1e-9]
            darcy = rows("darcy")
            n = darcy[0]["physical_nodes"] if darcy else V["n_interior"] + V["n_boundary"]
            setup = med([r["shared_setup_s"] + r["setup_s"] for r in darcy if r.get("setup_s")])
            fd = med([r["solve_s"] for r in darcy if r.get("solve_s")])
            frd = med([r["rollout_s"] for r in rows("rd") if r.get("rollout_s")])
            fad = med([r["rollout_s"] for r in rows("ad") if r.get("rollout_s")])
            ir = [med([r["fit_s"] for r in inv[prob] if r["geometry"] == g and r["order"] == p and abs(r["h"] - h) < 1e-9])
                  for prob in ("darcy", "rd", "transport")]
            name = capital(gname) if p == ORDERS[0] else ""
            nodes = fmt(tn) if p == ORDERS[0] else ""
            lines.append(f"{name} & {p} & {n} & {nodes} & {fmt(setup)} & {fmt(fd)} & {fmt(frd)} & {fmt(fad)} & "
                         + " & ".join(fmt(t) for t in ir) + r"\\")
        if gi == 0:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def geometry_data():
    """Geometry errors of scripts/paper_geometry_convergence.py: parametric layer vs input sample spacing delta,
    implicit layer vs CFPU site spacing h (paper range h >= .04)."""
    G = json.load(open(O / "paper_geometry_convergence_20261014/results.json"))
    def fit(x, y):
        a, c = np.polyfit(np.log(x), np.log(y), 1)
        return dict(a=float(a), c=float(c), x0=float(min(x)), x1=float(max(x)))
    out = {}
    for g, key in (("h_channel", "walls"), ("treasure_chest", "cap")):
        A = G[g]["A"]
        pieces = (lambda r: [r["wall_0"], r["wall_1"]]) if g == "h_channel" else (lambda r: [r["cap"]])
        x = [r["delta"] for r in A]
        dist = [max(p["dist_all"]["max"] for p in pieces(r)) for r in A]
        ang = [max(p["angle_deg_interior"]["max"] for p in pieces(r)) for r in A]
        B = [r for r in G[g]["B1"] if r["h"] >= 0.04 - 1e-9]
        hh = [r["h"] for r in B]
        far = [r["dphi_far2h"]["max"] for r in B]
        allp = [r["dphi_all"]["max"] for r in B]
        out[g] = dict(delta=x, dist=dist, angle=ang, h=hh, far=far, all=allp, paper=G["settings"]["paper_level"][g],
                      levels=[r["level"] for r in A], fit_dist=fit(x, dist), fit_angle=fit(x, ang),
                      fit_far=fit(hh, far), fit_all=fit(hh, allp))
    return out


def inverse_timings_data():
    """Wall-clock time of one fit (median over the families) against N, per problem; the coarsest cloud is a cold
    start, the others are warm starts. Least-squares fits on the treasure chest over the warm-started clouds."""
    out = {}
    for prob in ("darcy", "rd", "transport"):
        rows = [r for r in load_inverse(prob) if r["status"] == "ok" and r.get("fit_s")]
        series, fits = [], []
        for p in ORDERS:
            for g, _, _ in GEOMS:
                pts = {}
                for r in rows:
                    if r["geometry"] == g and r["order"] == p:
                        pts.setdefault(r["physical_nodes"], []).append(r["fit_s"])
                N = sorted(pts)
                series.append(dict(p=p, geometry=g, N=N, t=[float(np.median(pts[n])) for n in N]))
                if g == "treasure_chest":
                    warm = [(n, float(np.median(pts[n]))) for n in N[1:]]
                    a, c = np.polyfit(np.log([n for n, _ in warm]), np.log([t for _, t in warm]), 1)
                    fits.append(dict(p=p, a=float(a), c=float(c), N0=warm[0][0], N1=warm[-1][0]))
        out[prob] = dict(series=series, fits=fits)
    return out


