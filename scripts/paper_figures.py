def node_stack_data(h_nodes=.08):
    """Data of Figure node_stack (the stacked representation on the treasure chest), drawn by
    scripts/matlab/paper_plots.m. Reads Outputs_and_results/paper_figures/node_stack_chest.npz from
    scripts/paper_node_stack_data.py. (a) the cap's parameter domain with its cells, trimming loop, and one cell
    with its support; (b) the chest with the cap surface, the image of the support and its ball, boundary nodes
    facing the viewer and the ghost nodes in the ball; (c) the slice x_3 = 0 of the implicit layer: the balls
    cut by the slice and the background grid; (d) the nodes of the slab |x_3| < h/2."""
    from matplotlib.path import Path as Polygon
    L, D, A, B, P = 1.2, .6, .6, .35, 4
    z = np.load(O / "paper_figures/node_stack_chest.npz")
    cells, overlap, outline = z["cap_cells"], float(z["cap_overlap"]), z["cap_outline"]
    loop = Polygon(outline)
    ng = int(round(np.sqrt(len(z["cap_grid_z"]))))
    gx = z["cap_grid_x"].reshape(ng, ng, 3)

    def cap_map(uv):  # bilinear in the sampled grid of the cap map, uv in [-1, 1]^2
        t = (np.atleast_2d(uv) + 1) / 2 * (ng - 1)
        i = np.clip(np.floor(t).astype(int), 0, ng - 2)
        s = t - i
        return (gx[i[:, 0], i[:, 1]] * ((1 - s[:, 0]) * (1 - s[:, 1]))[:, None]
                + gx[i[:, 0] + 1, i[:, 1]] * (s[:, 0] * (1 - s[:, 1]))[:, None]
                + gx[i[:, 0], i[:, 1] + 1] * ((1 - s[:, 0]) * s[:, 1])[:, None]
                + gx[i[:, 0] + 1, i[:, 1] + 1] * (s[:, 0] * s[:, 1])[:, None])

    def masked(points, inside):
        x = np.array(points, dtype=float)
        x[~inside] = np.nan
        return x

    # highlighted cell: inside the loop, mapped close to a chosen point of the cap
    centers, half = (cells[:, :2] + cells[:, 2:]) / 2, (cells[:, 2:] - cells[:, :2]) / 2
    dist = np.linalg.norm(cap_map(centers) - np.array([L + .45, -.25, .22]), axis=1)
    dist[~loop.contains_points(centers)] = np.inf
    j = int(np.argmin(dist))
    cj, aj = centers[j], half[j]
    sj = overlap * aj
    # cap surface and the image of the support on regular parameter grids, NaN outside the trimming loop
    u = np.linspace(-1, 1, 41)
    U = np.stack(np.meshgrid(u, u, indexing="ij"), -1).reshape(-1, 2)
    cap = masked(cap_map(U), loop.contains_points(U)).reshape(41, 41, 3)
    us, vs = np.linspace(cj[0] - sj[0], cj[0] + sj[0], 31), np.linspace(cj[1] - sj[1], cj[1] + sj[1], 31)
    Us = np.stack(np.meshgrid(us, vs, indexing="ij"), -1).reshape(-1, 2)
    ins = loop.contains_points(Us)
    patch = masked(cap_map(Us), ins).reshape(31, 31, 3)
    y = cap_map(Us[ins])
    cb = y.mean(axis=0)
    rb = 1.25 * np.max(np.linalg.norm(y - cb, axis=1))
    th = np.linspace(0, 2 * np.pi, 193)
    rim = np.column_stack([np.full_like(th, L), A * np.sign(np.cos(th)) * np.abs(np.cos(th)) ** (2 / P),
                           B * np.sign(np.sin(th)) * np.abs(np.sin(th)) ** (2 / P)])
    view = np.array([0.50, -0.78, 0.45])
    view /= np.linalg.norm(view)
    xb, nb, xg, xi = z["bdry_nodes"], z["normals"], z["ghost_nodes"], z["int_nodes"]
    front = nb @ view > 0.15
    near = (np.linalg.norm(xb - cb, axis=1) < rb) & front
    # slice x_3 = z0 of the implicit layer
    z0, cell = float(z["slice_z"]), float(z["slice_cell"])
    cen, rad = z["ball_centers"], z["ball_radii"]
    hit = np.abs(cen[:, 2] - z0) < rad
    discs = np.unique(np.column_stack([cen[hit][:, :2], np.sqrt(rad[hit] ** 2 - (cen[hit][:, 2] - z0) ** 2)]).round(5), axis=0)
    sc, free, sign = z["slice_cells"], z["slice_free"], z["slice_sign"]
    yy = np.linspace(-A, A, 161)
    dome = np.column_stack([L + D * np.sqrt(np.clip(1 - np.abs(yy / A) ** P, 0, None)), yy])
    section = np.vstack([[0, -A], [L, -A], dome, [L, A], [0, A], [0, -A]])
    slab = lambda x: x[np.abs(x[:, 2]) < h_nodes / 2][:, :2].round(5).tolist()
    nan = lambda a: np.where(np.isnan(a), None, a.round(5)).tolist()
    return dict(
        cells=cells.round(5).tolist(), outline=outline[::10].round(5).tolist(),
        cell_j=[*(cj - aj), *(cj + aj)], support_j=[*(cj - sj), *(cj + sj)],
        cap=nan(cap), patch=nan(patch), ball_center=cb.round(5).tolist(), ball_radius=float(rb), rim=rim.round(5).tolist(),
        box=[0, L, -A, A, -B, B], view=view.tolist(),
        front_nodes=xb[front].round(5).tolist(), ghosts_near=xg[near].round(5).tolist(),
        discs=discs.tolist(), cell=cell, grid_lo=(sc.min(axis=0) - cell / 2).tolist(), grid_hi=(sc.max(axis=0) + cell / 2).tolist(),
        free_inside=sc[free & (sign > 0)].round(5).tolist(), section=section.round(5).tolist(),
        int_nodes=slab(xi), bdry_nodes=slab(xb), ghost_nodes=slab(xg))


def estimate_table(path):
    rows = [json.loads(l) for l in (F / "estimate_check.jsonl").read_text().splitlines()]
    lines = [r"\begin{table}", r"\centering",
             r"\caption{Quantities of the elliptic error estimate \eqref{eq:elliptic_bound} for the Darcy problem over the three finest clouds ($h\leq0.08$). "
             r"The columns give the least-squares slope of the truncation error $\norm{\tau}_2/\sqrt N$ against $N^{-1/d}$ (smallest and largest over the parameter families), "
             r"the range of the effective stability constant $\hat S_h$ of \eqref{eq:effective_stability}, and the largest scaled stencil sum $W_L$ of \eqref{eq:stencil_sums}.}",
             r"\label{tab:forward_estimate}", r"\begin{tabular}{llcccc}", r"\toprule",
             r"Geometry & $p$ & Slope of $\norm{\tau}$ & $\min\hat S_h$ & $\max\hat S_h$ & $\max W_L$\\", r"\midrule"]
    for gi, (g, gname, d) in enumerate(GEOMS):
        for p in ORDERS:
            rr = [r for r in rows if r["geometry"] == g and r["order"] == p and r["h"] <= H_FIT]
            slopes = []
            for fam in sorted({r["family"] for r in rr}):
                pts = [(r["h"], r["physical_nodes"] ** (-1 / d), r["tau_phys_l2"] / math.sqrt(r["physical_nodes"]))
                       for r in rr if r["family"] == fam]
                slopes.append(slope(pts))
            kap = [r["kappa"] for r in rr]
            name = capital(gname) if p == 2 else ""
            lines.append(f"{name} & {p} & {min(slopes):.1f}--{max(slopes):.1f} & {sci(min(kap))} & {sci(max(kap))} & {max(r['lam_L'] for r in rr):.0f}\\\\")
        if gi == 0:
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def efficiency_table(inv, path):
    """eta = ||theta_h - theta*|| sigma_min(J(theta_h)) / ||r(theta*)|| over the completed fits."""
    lines = [r"\begin{table}", r"\centering",
             r"\caption{The efficiency index $\eta$ of the first-order inverse error bound over all inverse solves.}",
             r"\label{tab:inverse_efficiency}", r"\begin{tabular}{llcccc}", r"\toprule",
             r"Problem & Geometry & Solves & $\min\eta$ & median $\eta$ & $\max\eta$\\", r"\midrule"]
    for item in inv:
        prob, name, rows = item[:3]
        for k, (g, gname, d) in enumerate(item[3] if len(item) > 3 else GEOMS):
            e = [r["parameter_rel_error"] * min(r["jacobian_singular_values"]) * np.linalg.norm(r["truth_theta"]) / r["objective_at_truth"]
                 for r in rows if r["geometry"] == g and r.get("jacobian_singular_values")]
            if not e:
                continue
            lines.append(f"{capital(name) if k == 0 else ''} & {gname} & {len(e)} & {min(e):.3f} & {np.median(e):.3f} & {max(e):.3f}" + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def obstacle_slice_data(h=.06):
    """Nodes of the treasure chest with an internal obstacle in the slab |x_3| < h/2, drawn by
    scripts/matlab/paper_plots.m (obstacle_slice)."""
    z = np.load(OBSTACLE_CLOUDS / f"obstacle_chest_h{h:.2f}_s11.npz")
    d = {}
    for name in ("int_nodes", "bdry_nodes", "ghost_nodes"):
        x = np.asarray(z[name])
        d[name] = x[np.abs(x[:, 2]) < h / 2][:, :2].round(5).tolist()
    d["h"] = h
    return d


